/** Код грани эффекта — один у образца (lib/products.ts) и у движка cbdin:
 *  по нему источник собирает эффекты (`Source.effects`), а страница эффекта
 *  ставит свой выбор и не показывает его среди граней. */
export const EFFECT_FACET = 'effect'

/** Эффекты движка, которых на витрине нет: ни плитки, ни страницы, ни
 *  строки в фильтрах и меню. Данные магазина, пока у значения грани в
 *  движке нет своего признака «не показывать» — тогда этот список уйдёт.
 *  `immunity` — слово заказчика 03.10.2026: «Immunity удаляй»; товары с ним
 *  остаются, они стоят и под другими эффектами. */
export const HIDDEN_EFFECTS: ReadonlySet<string> = new Set(['immunity'])
/** Значение грани показывается на витрине. */
export const onSite = (facet: string, value: string) => !(facet === EFFECT_FACET && HIDDEN_EFFECTS.has(value))
