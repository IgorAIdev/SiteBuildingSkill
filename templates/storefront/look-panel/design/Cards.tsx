export async function Cards({ lang }: { lang: Lang }) {
  const r = await source().listing(lang, { facets: {}, sort: 'popular', page: null })
  const items: Card[] = r.ok ? r.value.items : []
  /* Образец — товар, который назвал заказчик (30.09.2026, со снимком
     карточки: «поменяй товар в дизайн-системе на этот»): масло CBD+CBN 20 %
     движка cbdin — со снимком в руке, скидкой и дозой в капле. Нет его (у
     образца данных, в другом магазине) — масло со скидкой, где видно всё:
     всего мг, мера, доза и прежняя цена; нет и такого — первый товар полки. */
  const full = (c: Card) => shelfCard(lang, c).figures.length >= 3
  const named = await source().cards(lang, [SAMPLE])
  const one = (named.ok ? named.value[0] : undefined) ?? items.find((c) => full(c) && c.pick?.was) ?? items.find(full) ?? items[0]
  if (!one) return <Part title="Карточка товара" lede="Магазин не ответил — показать нечего.">{null}</Part>
  const card = shelfCard(lang, one)
  const cart = { submit: cartSubmit, call: cartCall }
  const { card: site } = await lookNow()
  return (
    <Bench first={site}>
      <Part title="Дизайн карточки" lede="Все дизайны карточки на одном товаре; под каждым — как он отвечает руке. Карточки — образцы: по ним не переходят и в корзину не кладут. Тень есть у дизайнов 3 и 4 — переключается тут же, это та же тень, что в панели Look. Отметка у имени ставит дизайн на сайт — так же, как выбор в панели Look, черновиком; и он же — основа раздела «Информация в карточке» ниже.">
        <ShadowSwitch />
        <ul id="design-dress" className={`${p.rail} ${s.row}`} data-rail="goods">
          {DRESS.map((d, i) => (
            <li key={d.id} className={s.cell}>
              <DressPick id={d.id} name={`Дизайн ${i + 1}`} />
              <ProductCard card={card} cart={cart} dress={d.id} eager sample />
              <States {...hand(d)} />
            </li>
          ))}
        </ul>
      </Part>
      <Part title="Информация в карточке" lede="Одна и та же карточка — от минимума к полноте: меняется только то, что стоит под именем. Показано на дизайне, отмеченном выше. Товар настоящий, из магазина.">
        {DRESS.map(({ id: dress }) => (
          <ForDress key={dress} id={dress}>
            <ul id="design-cards" className={`${p.rail} ${s.row}`} data-rail="goods">
              {INFO.map(([info, line], i) => (
                <li key={info} className={s.cell}>
                  <p className={s.cellName}>Вид {i + 1}</p>
                  <ProductCard card={card} cart={cart} info={info} dress={dress} eager={false} sample />
                  <p className={p.note}>{line}</p>
                </li>
              ))}
            </ul>
          </ForDress>
        ))}
      </Part>
      <Sizes />
    </Bench>
  )
}
