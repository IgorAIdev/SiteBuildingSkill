/** Вектор — адрес SVG: файл `.svg` или `data:image/svg+xml`. Семья
 *  `weight` меряет отданные ПИКСЕЛИ, а у вектора их нет: рисунок один на
 *  любой размер, байты не растут с местом. Его `naturalWidth` — не вес, а
 *  размер по умолчанию (150 у SVG без своих `width`/`height`), и сравнивать
 *  его с местом значит считать долгом то, чего нет (И264). Адрес на `.svg`
 *  с параметром формата в запросе (`fm=png` — imgix, Contentful, Sanity;
 *  `format=webp` — Shopify, Cloudflare) CDN отдаёт растром — это не вектор,
 *  его вес меряется; `format=svg` вектор не отменяет. Регулярным
 *  выражением, потому что уезжает в страницу строкой: замер импортировать
 *  не умеет. */
export const VECTOR = /^data:image\/svg\+xml[;,]|\.svg(?:#|$|\?(?!(?:[^#]*&)?(?:fm|format)=(?!svg(?:[&#]|$))))/i

